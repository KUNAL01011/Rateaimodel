export const getFeaturedTools = () => MOCK_TOOLS.filter(t => t.featured);
export const getTrendingTools = () => MOCK_TOOLS.filter(t => t.trending);
export const getToolBySlug = (slug: string) =>
  MOCK_TOOLS.find(t => t.slug === slug);
export const getToolsByCategory = (category: string) =>
  MOCK_TOOLS.filter(t => t.category.toLowerCase() === category.toLowerCase());
export const searchTools = (query: string) => {
  const q = query.toLowerCase();
  return MOCK_TOOLS.filter(
    t =>
      t.name.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.tags.some(tag => tag.includes(q)) ||
      t.category.toLowerCase().includes(q)
  );
};
